#!/usr/bin/env python3
"""Render a facade package's aliases of internal types like declared types.

runtime/pipeline/stage is being split into stage/internal/<name> packages whose
types stage re-exports as aliases (#2876). gomarkdoc renders an alias as its
one-line declaration, `type X = core.X`, so every moved type would lose its
fields, its doc and its methods from the reference page, although they are
exactly what a stage.X user calls. This puts them back: for each alias section
in the facade page whose target section exists in one of the internal pages,
the internal section (doc, declaration, source link) replaces the alias's, its
methods follow the facade's own functions for the type, and the index gains
the method entries. A page without such an alias is printed unchanged.

Usage: splice-aliases.py FACADE.md INTERNAL.md... > OUT.md
"""

import re
import sys

ANCHOR_LINE = re.compile(r'^<a name="([^"]+)"></a>$')
ANY_ANCHOR = re.compile(r'^<a name="([^"]+)"></a>')
INLINE_ANCHOR = re.compile(r'^<a name="([^"]+)"></a>.')
IMPORT_LINE = re.compile(r'^import "([^"]+)"$')
ALIAS_DECL = re.compile(r"^type ([A-Za-z0-9_]+) = ([A-Za-z0-9_]+)\.([A-Za-z0-9_]+)$")
FOOTER = "Generated by [gomarkdoc]"


class Section:
    """A heading with its anchor line and body, up to the next heading."""

    def __init__(self, anchor, level):
        self.anchor = anchor
        self.level = level  # 2 for "## ", 3 for "### "
        self.lines = []


class Page:
    """A gomarkdoc file: what precedes the first heading section (the title,
    the index, the package-level constants and variables), the sections in
    order, then the "Generated by gomarkdoc" footer."""

    def __init__(self, path):
        with open(path, encoding="utf-8") as f:
            lines = f.read().split("\n")
        self.pkg = ""   # the package name, from the "# name" title
        self.path = ""  # the import path, from the import line under it
        self.preamble, self.sections, self.footer = [], [], []
        cur = None
        for i, line in enumerate(lines):
            if line.startswith(FOOTER) or self.footer:
                self.footer.append(line)
                continue
            if not self.pkg and line.startswith("# "):
                self.pkg = line[2:]
            m = IMPORT_LINE.match(line)
            if m and not self.path:
                self.path = m.group(1)
            m = ANCHOR_LINE.match(line)
            if m and i + 1 < len(lines):
                nxt = lines[i + 1]
                level = 2 if nxt.startswith("## ") else 3 if nxt.startswith("### ") else 0
                if level:
                    cur = Section(m.group(1), level)
                    self.sections.append(cur)
            (cur.lines if cur else self.preamble).append(line)

    def type_group(self, name):
        """The [start, end) of the type section named name and its function
        and method subsections, or None."""
        for i, s in enumerate(self.sections):
            if s.level == 2 and s.anchor == name and s.lines[1].startswith("## type "):
                end = i + 1
                while end < len(self.sections) and self.sections[end].level == 3:
                    end += 1
                return i, end
        return None

    def anchors(self):
        taken = set()
        for line in self.preamble + [l for s in self.sections for l in s.lines]:
            m = ANY_ANCHOR.match(line)
            if m:
                taken.add(m.group(1))
        return taken

    def render(self):
        out = self.preamble + [l for s in self.sections for l in s.lines] + self.footer
        return "\n".join(out)


def alias_target(section):
    """The (package, type) a section's declaration aliases under its own name."""
    for line in section.lines:
        m = ALIAS_DECL.match(line)
        if m and m.group(1) == section.anchor and m.group(3) == section.anchor:
            return m.group(2), m.group(3)
    return None


def index_children(lines, name):
    """Where the entries under "- [type name]" end, and the entries."""
    head = "- [type %s](<#%s>)" % (name, name)
    for i, line in enumerate(lines):
        if line == head:
            j = i + 1
            while j < len(lines) and lines[j].startswith("  - "):
                j += 1
            return j, lines[i + 1 : j]
    return -1, []


def without_anchors(lines, taken):
    """Drops the inline-anchored blocks (typed constants and variables gomarkdoc
    lists under their type) whose anchor the facade already renders, so each
    anchor appears once on the page; the blank line after each goes too."""
    out, skipping, fences = [], False, 0
    for i, line in enumerate(lines):
        m = INLINE_ANCHOR.match(line)
        if i > 0 and m and m.group(1) in taken:
            skipping, fences = True, 0
        if skipping and fences == 2:
            skipping = False
            if line == "":
                continue
        if not skipping:
            out.append(line)
        elif line.startswith("```"):
            fences += 1
    return out


def examples(lines):
    """The facade section's example blocks (gomarkdoc's <details>), each with
    the blank line after it."""
    out, inside = [], False
    for i, line in enumerate(lines):
        if line.startswith("<details><summary>Example"):
            inside = True
        if inside:
            out.append(line)
            if line == "</details>":
                inside = False
                if i + 1 < len(lines) and lines[i + 1] == "":
                    out.append("")
    return out


def splice(facade, internals):
    taken = facade.anchors()
    i = 0
    while i < len(facade.sections):
        s = facade.sections[i]
        target = alias_target(s) if s.level == 2 else None
        src = None
        if target:
            # The alias names its package by name; the internal pages are keyed
            # by import path, and two internal packages may share a name.
            found = [p for p in internals.values() if p.pkg == target[0]]
            if len(found) > 1:
                raise SystemExit("splice-aliases: %s aliases %s.%s, and %s are all named %s"
                                 % (s.anchor, target[0], target[1],
                                    ", ".join(sorted(p.path for p in found)), target[0]))
            src = found[0] if found else None
        group = src.type_group(target[1]) if src else None
        if not group:
            i += 1
            continue
        name = target[1]
        start, end = group
        _, f_end = facade.type_group(name)

        head = src.sections[start]
        # The facade's own type section goes; the typed constants and
        # variables it listed under the type are the internal section's too,
        # so only anchors rendered elsewhere on the page are dropped from it.
        here = {m.group(1) for m in map(ANY_ANCHOR.match, s.lines[1:]) if m}
        head.lines = without_anchors(head.lines, taken - here)
        taken |= {m.group(1) for m in map(ANY_ANCHOR.match, head.lines) if m}
        # Examples live in the facade's tests, so only its page has them.
        head.lines = head.lines + examples(s.lines)
        own = facade.sections[i + 1 : f_end]
        own_anchors = {o.anchor for o in own}
        methods = [
            m for m in src.sections[start + 1 : end]
            if m.anchor.startswith(name + ".") and m.anchor not in own_anchors
        ]
        new = [head] + own + methods
        facade.sections[i:f_end] = new
        i += len(new)

        at, children = index_children(facade.preamble, name)
        if at < 0:
            continue
        _, src_children = index_children(src.preamble, name)
        add = [c for c in src_children if "(<#%s." % name in c and c not in children]
        facade.preamble[at:at] = add


def main(argv):
    if len(argv) < 2:
        sys.stderr.write("usage: splice-aliases.py FACADE.md INTERNAL.md...\n")
        return 2
    facade = Page(argv[1])
    internals = {}  # by import path
    for path in argv[2:]:
        p = Page(path)
        if not p.path:
            sys.stderr.write("splice-aliases: no import line in %s\n" % path)
            return 1
        internals[p.path] = p
    splice(facade, internals)
    sys.stdout.write(facade.render())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
