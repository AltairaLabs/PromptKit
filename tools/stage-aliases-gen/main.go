// Command stage-aliases-gen writes the file through which
// runtime/pipeline/stage re-exports what moved into one of its stage/internal
// packages (#2876):
//
//   - a type becomes an alias:          type X = core.X
//   - a function becomes a wrapper:     func F(a A) B { return core.F(a) }
//   - a var (a sentinel error):         var ErrX = core.ErrX
//   - a const keeps its type, if any:   const X T = core.X
//
// Each keeps the doc comment of its declaration. Only the names stage exported
// before the move are re-exported, so what an internal package exports for
// stage's own use stays out of stage's API. Those names are read from a copy of
// stage's source from before the move (-base).
//
// Run it through scripts/gen-stage-aliases.sh (make stage-aliases PKG=core).
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"io"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"
)

// outputPerm is the mode a newly written file gets (git keeps no more).
const outputPerm = 0o600

func main() {
	if err := run(os.Args[1:], os.Stdout); err != nil {
		fmt.Fprintln(os.Stderr, "stage-aliases-gen:", err)
		os.Exit(1)
	}
}

// run parses the flags, generates the file and reports what it re-exported.
func run(args []string, stdout io.Writer) error {
	fs := flag.NewFlagSet("stage-aliases-gen", flag.ContinueOnError)
	base := fs.String("base", "", "stage's source dir from before the move")
	pkgDir := fs.String("pkg", "", "the internal package's dir")
	importPath := fs.String("import", "", "the internal package's import path")
	out := fs.String("out", "", "the file to write")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if *base == "" || *pkgDir == "" || *importPath == "" || *out == "" {
		return errors.New("-base, -pkg, -import and -out are all required")
	}
	before, aliases, err := exportedNames(*base)
	if err != nil {
		return err
	}
	src, n, err := generate(*pkgDir, *importPath, before, aliases)
	if err != nil {
		return err
	}
	if writeErr := os.WriteFile(*out, src, outputPerm); writeErr != nil {
		return writeErr
	}
	_, err = fmt.Fprintf(stdout, "%s: %d names re-exported from %s\n", *out, n, *importPath)
	return err
}

// generate is the re-export file for the package in dir, and how many names it
// re-exports: those in before. aliases are stage's type aliases at base (see
// exportedNames).
func generate(dir, importPath string, before map[string]bool, aliases map[string]string) ([]byte, int, error) {
	fset := token.NewFileSet()
	files, err := parseDir(fset, dir)
	if err != nil {
		return nil, 0, err
	}
	g := &generator{
		fset: fset, q: path.Base(importPath), internalDir: path.Dir(importPath),
		before: before, aliases: aliases, imports: map[string]bool{},
	}
	for _, f := range files {
		for _, d := range f.file.Decls {
			if declErr := g.decl(f, d); declErr != nil {
				return nil, 0, declErr
			}
		}
	}
	if g.plain {
		g.imports[importPath] = true
	}
	if g.shadowed {
		for p := range g.imports {
			if p != importPath && path.Base(p) == g.shadowQ() {
				return nil, 0, fmt.Errorf("%s: %s names both the package's second import and another import",
					g.shadowUser, g.shadowQ())
			}
		}
	}
	var head bytes.Buffer
	fmt.Fprintf(&head, "// Code generated by tools/stage-aliases-gen from %s; DO NOT EDIT.\n\n", importPath)
	head.WriteString("package stage\n\nimport (\n")
	paths := make([]string, 0, len(g.imports))
	for p := range g.imports {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		fmt.Fprintf(&head, "\t%q\n", p)
	}
	if g.shadowed {
		fmt.Fprintf(&head, "\t%s %q\n", g.shadowQ(), importPath)
	}
	head.WriteString(")\n")
	formatted, err := format.Source(append(head.Bytes(), g.body.Bytes()...))
	if err != nil {
		return nil, 0, fmt.Errorf("format: %w", err)
	}
	return formatted, g.n, nil
}

type generator struct {
	fset        *token.FileSet
	q           string // the internal package's name, as stage qualifies it
	internalDir string // the dir of stage's internal packages
	before      map[string]bool
	aliases     map[string]string // stage's alias name -> "importpath.Name" it aliases
	imports     map[string]bool
	plain       bool   // something calls or aliases through q: the package is imported as itself
	shadowed    bool   // a wrapper's parameter or result hides q: the package is imported again as shadowQ
	shadowUser  string // the first such wrapper, for an error
	body        bytes.Buffer
	n           int
}

// shadowQ is the second name the internal package is imported by, for the
// wrappers with a parameter or named result named like the package
// (NewProviderStage's provider): in them q is that name, and renaming it
// instead would change stage's documented signature. The package is imported
// as itself only when something else uses that name, and generation fails
// when shadowQ is itself taken, by the wrapper or by another import.
func (g *generator) shadowQ() string {
	return g.q + "pkg"
}

// namedIn reports whether a parameter or a named result of ft is named name:
// wrapper copies both into the wrapper's signature.
func namedIn(ft *ast.FuncType, name string) bool {
	for _, list := range []*ast.FieldList{ft.Params, ft.Results} {
		if list == nil {
			continue
		}
		for _, field := range list.List {
			for _, id := range field.Names {
				if id.Name == name {
					return true
				}
			}
		}
	}
	return false
}

func (g *generator) decl(f srcFile, d ast.Decl) error {
	switch d := d.(type) {
	case *ast.FuncDecl:
		if d.Recv != nil || !g.before[d.Name.Name] {
			return nil
		}
		if d.Type.TypeParams != nil {
			return fmt.Errorf("%s: generic function; write its wrapper by hand", d.Name.Name)
		}
		facade, err := g.facadeSelectors(f.file, d.Type)
		if err != nil {
			return fmt.Errorf("%s: %w", d.Name.Name, err)
		}
		paths, err := importsUsed(f.file, d.Type, facade)
		if err != nil {
			return err
		}
		for _, p := range paths {
			g.imports[p] = true
		}
		g.n++
		text := func(n ast.Node) string { return f.textUnqualified(g.fset, n, facade) }
		q := g.q
		if namedIn(d.Type, g.q) {
			if namedIn(d.Type, g.shadowQ()) {
				return fmt.Errorf("%s: %s names both the package's second import and a parameter or result",
					d.Name.Name, g.shadowQ())
			}
			q = g.shadowQ()
			if !g.shadowed {
				g.shadowed, g.shadowUser = true, d.Name.Name
			}
		} else {
			g.plain = true
		}
		g.body.WriteString("\n" + doc(d.Doc) + wrapper(text, d, q) + "\n")
	case *ast.GenDecl:
		return g.genDecl(f, d)
	}
	return nil
}

// genDecl writes the re-exported specs of a type, var or const declaration,
// as one declaration when it had one spec and as a group otherwise.
func (g *generator) genDecl(f srcFile, d *ast.GenDecl) error {
	var specs []string
	// A const in a group with neither type nor value repeats the one before it
	// (iota), so its type does too.
	constType := ""
	for _, s := range d.Specs {
		dc, line, err := g.spec(f, d, s, &constType)
		if err != nil {
			return err
		}
		if line == "" {
			continue
		}
		if dc == nil && len(d.Specs) == 1 {
			dc = d.Doc
		}
		specs = append(specs, doc(dc)+line)
	}
	if len(specs) == 0 {
		return nil
	}
	kw := d.Tok.String()
	if len(specs) == 1 && len(d.Specs) == 1 {
		s := specs[0]
		last := s[strings.LastIndex(s, "\n")+1:]
		g.body.WriteString("\n" + s[:len(s)-len(last)] + kw + " " + last + "\n")
		return nil
	}
	g.body.WriteString("\n" + doc(d.Doc) + kw + " (\n" + strings.Join(specs, "\n") + "\n)\n")
	return nil
}

// spec is one spec's doc and re-export line ("" when it re-exports nothing).
func (g *generator) spec(f srcFile, d *ast.GenDecl, s ast.Spec, constType *string) (*ast.CommentGroup, string, error) {
	switch s := s.(type) {
	case *ast.TypeSpec:
		if !g.before[s.Name.Name] {
			return nil, "", nil
		}
		if s.TypeParams != nil {
			return nil, "", fmt.Errorf("%s: generic type; write its alias by hand", s.Name.Name)
		}
		g.n++
		g.plain = true
		return s.Doc, fmt.Sprintf("%s = %s.%s", s.Name.Name, g.q, s.Name.Name), nil
	case *ast.ValueSpec:
		return s.Doc, g.valueSpec(f, d.Tok, s, constType), nil
	}
	return nil, "", nil
}

// valueSpec is the re-export line of a var or const spec ("" for none). A
// typed const keeps its type, so the reference page still lists it under that
// type.
func (g *generator) valueSpec(f srcFile, tok token.Token, s *ast.ValueSpec, constType *string) string {
	typ := ""
	if tok == token.CONST {
		if s.Type != nil || len(s.Values) > 0 {
			*constType = ""
			if s.Type != nil {
				*constType = " " + f.text(g.fset, s.Type)
			}
		}
		typ = *constType
	}
	var lines []string
	for _, id := range s.Names {
		if g.before[id.Name] {
			g.n++
			g.plain = true
			lines = append(lines, fmt.Sprintf("%s%s = %s.%s", id.Name, typ, g.q, id.Name))
		}
	}
	return strings.Join(lines, "\n")
}

// facadeSelectors are the qualified names in n from a sibling stage/internal
// package. Each must be one stage aliases under the same name (type X =
// sibling.X), so the wrapper names it as stage does and its signature reads as
// it did before the move. A sibling name stage does not alias is an error: left
// qualified, it would put an internal package into stage's API.
func (g *generator) facadeSelectors(f *ast.File, n ast.Node) (map[*ast.SelectorExpr]bool, error) {
	byName := importNames(f)
	out := map[*ast.SelectorExpr]bool{}
	var bad error
	ast.Inspect(n, func(x ast.Node) bool {
		sel, ok := x.(*ast.SelectorExpr)
		if !ok {
			return true
		}
		id, ok := sel.X.(*ast.Ident)
		if !ok {
			return true
		}
		p, ok := byName[id.Name]
		if !ok || path.Dir(p) != g.internalDir {
			return true
		}
		if g.aliases[sel.Sel.Name] != p+"."+sel.Sel.Name {
			if bad == nil {
				bad = fmt.Errorf("%s.%s: stage has no alias %s = %s.%s; add one before re-exporting this",
					id.Name, sel.Sel.Name, sel.Sel.Name, id.Name, sel.Sel.Name)
			}
			return true
		}
		out[sel] = true
		return true
	})
	return out, bad
}

// importNames maps each import of f to the name the file qualifies it by.
func importNames(f *ast.File) map[string]string {
	byName := map[string]string{}
	for _, is := range f.Imports {
		p := strings.Trim(is.Path.Value, `"`)
		name := path.Base(p)
		if len(name) > 1 && name[0] == 'v' && strings.Trim(name[1:], "0123456789") == "" {
			name = path.Base(path.Dir(p)) // a major-version suffix: .../types/v2
		}
		if is.Name != nil {
			name = is.Name.Name
		}
		byName[name] = p
	}
	return byName
}

// importsUsed are the import paths of f that the package qualifiers in n name,
// apart from the qualifiers of skip.
func importsUsed(f *ast.File, n ast.Node, skip map[*ast.SelectorExpr]bool) ([]string, error) {
	byName := importNames(f)
	var paths []string
	var missing error
	ast.Inspect(n, func(x ast.Node) bool {
		sel, ok := x.(*ast.SelectorExpr)
		if !ok || skip[sel] {
			return true
		}
		if id, ok := sel.X.(*ast.Ident); ok {
			if p, ok := byName[id.Name]; ok {
				paths = append(paths, p)
			} else if missing == nil {
				missing = fmt.Errorf("%s.%s: no import named %s", id.Name, sel.Sel.Name, id.Name)
			}
		}
		return true
	})
	return paths, missing
}

type srcFile struct {
	file *ast.File
	src  []byte
}

// text is the source of n.
func (f srcFile) text(fset *token.FileSet, n ast.Node) string {
	return string(f.src[fset.Position(n.Pos()).Offset:fset.Position(n.End()).Offset])
}

// textUnqualified is the source of n with the package qualifier of each
// selector in unqualify left out.
func (f srcFile) textUnqualified(fset *token.FileSet, n ast.Node, unqualify map[*ast.SelectorExpr]bool) string {
	start, end := fset.Position(n.Pos()).Offset, fset.Position(n.End()).Offset
	var cuts []int // offsets of the qualifiers to drop, each up to its Sel
	ast.Inspect(n, func(x ast.Node) bool {
		if sel, ok := x.(*ast.SelectorExpr); ok && unqualify[sel] {
			cuts = append(cuts, fset.Position(sel.X.Pos()).Offset, fset.Position(sel.Sel.Pos()).Offset)
		}
		return true
	})
	var b strings.Builder
	at := start
	for i := 0; i < len(cuts); i += 2 {
		b.Write(f.src[at:cuts[i]])
		at = cuts[i+1]
	}
	b.Write(f.src[at:end])
	return b.String()
}

// parseDir parses a package's non-test files, in name order.
func parseDir(fset *token.FileSet, dir string) ([]srcFile, error) {
	matches, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}
	sort.Strings(matches)
	var files []srcFile
	for _, m := range matches {
		if strings.HasSuffix(m, "_test.go") {
			continue
		}
		src, err := os.ReadFile(m) //nolint:gosec // a file of the dir the caller named
		if err != nil {
			return nil, err
		}
		f, err := parser.ParseFile(fset, m, src, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		files = append(files, srcFile{f, src})
	}
	if len(files) == 0 {
		return nil, fmt.Errorf("%s: no Go files", dir)
	}
	return files, nil
}

// exportedNames are the exported package-level names declared in dir, and,
// for each that is an alias of a qualified type (type X = pkg.Y), what it
// aliases as "importpath.Y".
func exportedNames(dir string) (map[string]bool, map[string]string, error) {
	files, err := parseDir(token.NewFileSet(), dir)
	if err != nil {
		return nil, nil, err
	}
	names := map[string]bool{}
	aliases := map[string]string{}
	for _, f := range files {
		byName := importNames(f.file)
		for _, d := range f.file.Decls {
			for _, id := range declNames(d) {
				if id.IsExported() {
					names[id.Name] = true
				}
			}
			addAliases(aliases, d, byName)
		}
	}
	return names, aliases, nil
}

// addAliases records each exported alias of a qualified type that d declares.
func addAliases(aliases map[string]string, d ast.Decl, byName map[string]string) {
	gd, ok := d.(*ast.GenDecl)
	if !ok {
		return
	}
	for _, s := range gd.Specs {
		ts, ok := s.(*ast.TypeSpec)
		if !ok || !ts.Assign.IsValid() || !ts.Name.IsExported() {
			continue
		}
		sel, ok := ts.Type.(*ast.SelectorExpr)
		if !ok {
			continue
		}
		if q, ok := sel.X.(*ast.Ident); ok && byName[q.Name] != "" {
			aliases[ts.Name.Name] = byName[q.Name] + "." + sel.Sel.Name
		}
	}
}

// declNames are the package-level names d declares (none for a method).
func declNames(d ast.Decl) []*ast.Ident {
	switch d := d.(type) {
	case *ast.FuncDecl:
		if d.Recv == nil {
			return []*ast.Ident{d.Name}
		}
	case *ast.GenDecl:
		var ids []*ast.Ident
		for _, s := range d.Specs {
			switch s := s.(type) {
			case *ast.TypeSpec:
				ids = append(ids, s.Name)
			case *ast.ValueSpec:
				ids = append(ids, s.Names...)
			}
		}
		return ids
	}
	return nil
}

func doc(cg *ast.CommentGroup) string {
	if cg == nil {
		return ""
	}
	var b strings.Builder
	for _, c := range cg.List {
		b.WriteString(c.Text + "\n")
	}
	return b.String()
}

// wrapper is a function with d's signature that calls q.d. Every type the
// signature names from its own package is itself re-exported under the same
// name, so the signature means the same in stage; one that is not fails to
// compile there, which is the check. A type from a sibling internal package
// that stage aliases is named as stage names it; one it does not alias is an
// error (see facadeSelectors).
func wrapper(text func(ast.Node) string, d *ast.FuncDecl, q string) string {
	params, args := passParams(text, d.Type.Params)
	results := ""
	if r := d.Type.Results; r != nil {
		results = " " + text(r)
		if len(r.List) == 1 && len(r.List[0].Names) == 0 {
			results = " " + text(r.List[0].Type)
		}
	}
	call := fmt.Sprintf("%s.%s(%s)", q, d.Name.Name, strings.Join(args, ", "))
	if d.Type.Results != nil {
		call = "return " + call
	}
	return fmt.Sprintf("func %s(%s)%s {\n%s\n}", d.Name.Name, strings.Join(params, ", "), results, call)
}

// passParams are a parameter list's declarations and the arguments that pass
// them on. An unnamed or blank parameter is named argN, so it can be passed.
func passParams(text func(ast.Node) string, list *ast.FieldList) (params, args []string) {
	i := 0
	for _, field := range list.List {
		_, variadic := field.Type.(*ast.Ellipsis)
		n := max(len(field.Names), 1)
		var names []string
		for k := range n {
			name := fmt.Sprintf("arg%d", i)
			if k < len(field.Names) && field.Names[k].Name != "_" {
				name = field.Names[k].Name
			}
			i++
			names = append(names, name)
			if variadic {
				args = append(args, name+"...")
			} else {
				args = append(args, name)
			}
		}
		params = append(params, strings.Join(names, ", ")+" "+text(field.Type))
	}
	return params, args
}
